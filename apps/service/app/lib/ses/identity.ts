/**
 * SES Identity operations — create, get, delete domain identities.
 *
 * Uses EasyDKIM (AWS_SES signing origin): AWS generates and rotates DKIM keys.
 * After identity creation, GetEmailIdentity returns DkimAttributes.Tokens —
 * three CNAME hostnames the customer must publish.  No private-key handling
 * on our side.
 */

import {
  AlreadyExistsException,
  CreateEmailIdentityCommand,
  GetEmailIdentityCommand,
  DeleteEmailIdentityCommand,
  PutEmailIdentityDkimSigningAttributesCommand,
  type GetEmailIdentityCommandOutput,
} from '@aws-sdk/client-sesv2';
import { getSesClient } from './client';

export interface DkimAttributes {
  status: string;
  tokens: string[];
  signingEnabled: boolean;
}

export interface IdentityInfo {
  name: string;
  verifiedForSending: boolean;
  dkim: DkimAttributes;
}

export interface CreateIdentityResult {
  dkimTokens: string[];
}

/**
 * Create a new SES email identity for the given domain and enable EasyDKIM.
 * Returns the three CNAME DKIM token strings generated by AWS.
 */
export async function createIdentity({
  domain,
  region,
}: {
  domain: string;
  region?: string;
}): Promise<CreateIdentityResult> {
  await registerDomainIdentity({ domain, region });

  // SES may auto-configure EasyDKIM (AWS_SES origin) during CreateEmailIdentity,
  // populating DkimAttributes.Tokens immediately. If so, the subsequent Put call
  // is redundant and SES rejects it with "Signing key length parameter is null or empty".
  const afterCreate = await getIdentity({ domain, region });
  if (afterCreate.dkim.tokens.length > 0) {
    return { dkimTokens: afterCreate.dkim.tokens };
  }

  // Tokens not yet populated — explicitly enable EasyDKIM and re-fetch.
  await enableEasyDkim({ domain, region });
  const info = await getIdentity({ domain, region });
  return { dkimTokens: info.dkim.tokens };
}

async function registerDomainIdentity({
  domain,
  region,
}: {
  domain: string;
  region?: string;
}): Promise<void> {
  const client = getSesClient(region);
  try {
    await client.send(new CreateEmailIdentityCommand({ EmailIdentity: domain }));
  } catch (err) {
    if (err instanceof AlreadyExistsException) return;
    throw err;
  }
}

/**
 * Enable EasyDKIM on the identity: AWS_SES origin means AWS generates and rotates keys.
 */
async function enableEasyDkim({
  domain,
  region,
}: {
  domain: string;
  region?: string;
}): Promise<void> {
  const client = getSesClient(region);
  await client.send(
    new PutEmailIdentityDkimSigningAttributesCommand({
      EmailIdentity: domain,
      SigningAttributesOrigin: 'AWS_SES',
    }),
  );
}

/**
 * Retrieve identity and DKIM status from SES.
 */
export async function getIdentity({
  domain,
  region,
}: {
  domain: string;
  region?: string;
}): Promise<IdentityInfo> {
  const client = getSesClient(region);
  const response: GetEmailIdentityCommandOutput = await client.send(
    new GetEmailIdentityCommand({ EmailIdentity: domain }),
  );

  return {
    name: domain,
    verifiedForSending: response.VerifiedForSendingStatus ?? false,
    dkim: {
      status: response.DkimAttributes?.Status ?? 'NOT_STARTED',
      tokens: response.DkimAttributes?.Tokens ?? [],
      signingEnabled: response.DkimAttributes?.SigningEnabled ?? false,
    },
  };
}

/**
 * Delete the SES identity for the given domain.
 */
export async function deleteIdentity({
  domain,
  region,
}: {
  domain: string;
  region?: string;
}): Promise<void> {
  const client = getSesClient(region);
  await client.send(new DeleteEmailIdentityCommand({ EmailIdentity: domain }));
}
